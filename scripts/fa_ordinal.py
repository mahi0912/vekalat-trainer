"""تبدیل عدد ترتیبی فارسی («چهل و چهارم») به عدد."""
import re
UNITS = {"یک":1,"اول":1,"اوّل":1,"یکم":1,"دو":2,"دوم":2,"سه":3,"سوم":3,"چهار":4,"چهارم":4,
 "پنج":5,"پنجم":5,"شش":6,"ششم":6,"شص":6,"هفت":7,"هفتم":7,"هشت":8,"هشتم":8,"نه":9,"نهم":9}
TENS = {"ده":10,"دهم":10,"یازده":11,"یازدهم":11,"دوازده":12,"دوازدهم":12,"سیزده":13,"سیزدهم":13,
 "چهارده":14,"چهاردهم":14,"پانزده":15,"پانزدهم":15,"شانزده":16,"شانزدهم":16,"هفده":17,"هفدهم":17,
 "هجده":18,"هجدهم":18,"نوزده":19,"نوزدهم":19,"بیست":20,"بیستم":20,"سی":30,"سی‌ام":30,"سیم":30,
 "چهل":40,"چهلم":40,"پنجاه":50,"پنجاهم":50,"شصت":60,"شصتم":60,"هفتاد":70,"هفتادم":70,
 "هشتاد":80,"هشتادم":80,"نود":90,"نودم":90}
HUND = {"صد":100,"صدم":100,"یکصد":100,"یکصدم":100,"دویست":200,"دویستم":200,"سیصد":300,"سیصدم":300,
 "چهارصد":400,"پانصد":500,"ششصد":600,"هفتصد":700,"هشتصد":800,"نهصد":900}
ALL = {}; ALL.update(HUND); ALL.update(TENS); ALL.update(UNITS)
WORD = sorted(ALL, key=len, reverse=True)
TOKEN = re.compile("|".join(re.escape(w) for w in WORD))

def parse_ordinal(s):
    """رشته‌ای مثل «چهل و چهارم» → 44 ؛ اگر نشد None."""
    s = s.replace("ٔ", "").strip()
    parts = [p for p in re.split(r"\s+و\s+", s) if p]
    total, ok = 0, False
    for p in parts:
        p = p.strip()
        if p in ALL:
            total += ALL[p]; ok = True
        else:
            m = TOKEN.fullmatch(p)
            if m: total += ALL[m.group(0)]; ok = True
            else: return None
    return total if ok and 0 < total < 1400 else None
